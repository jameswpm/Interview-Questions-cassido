    # Short arrays
    assert check_alternate([1, 2]) == True
    assert check_alternate([1, 2, 2]) == False
    assert check_alternate([1, 1, 2]) == False

    # Repetition patterns
    assert check_alternate([3, 3, 3, 3]) == True
    assert check_alternate([4, 5, 4, 5]) == True
    assert check_alternate([4, 5, 4, 6]) == False

